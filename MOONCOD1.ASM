;--------------------------------
; FILE>MOON.CODE.1
;--------------------------------
COLD_START SEI ; TURN OFF INTERRUPTS
JSR INIT_IO ; SETUP I/O HARDWARE
LDA #$00
TAX
_1 .byte $9D ; OPCODE FOR STA $ZZZZ,X
.word TEMP1 ; BYTES FOR ADDRESS OF STA
STA $D000,X ; CLEAR 6566 VIDEO REGISTERS
STA $D400,X ; CLEAR 6581 SID REGISTERS
INX
BNE _1
TXS ; RESET STACK POINTER
JSR INIT_HARDWARE
JSR INIT_GAME
;--------------------------------
; DO THE GALAXY SCREEN
;--------------------------------
GALAXY_LOOP JSR HYPER_SPACE ; DO HYPERSPACE PICTURE
JSR MOVE_SCREEN ; PUT IN UNIVERSE
JSR PICK_GALAXY ; GET GALAXY CHOSEN
JSR HYPER_SPACE ; DO HYPERSPACE PICTURE
JSR MOVE_SCREEN ; PUT IN ORBIT
;--------------------------------
; DO THE ORBIT SCREEN
;--------------------------------
JSR INIT_ORBIT ; SET UP ORBIT SCREEN
;--------------------------------
; ORBIT LOOP
;--------------------------------
ORBIT_LOOP JSR DO_SHIP ; UPDATE SHIP
JSR DO_FUEL ; UPDATE FUEL
JSR BLOW_UP_SHIP ; KILL SHIP IF NEEDED
JSR UPDATE_SHOT ; UPDATE A SHOT
JSR DO_ORBIT ; MOVE ORBIT SPRITES
JSR COLLISION_DETECT ; CHECK FOR COLLISIONS
JSR DO_SOUNDS
JMP ORBIT_LOOP ; DO IT AGAIN
;--------------------------------
; INITIALIZE ORBIT SCENE
;--------------------------------
INIT_ORBIT LDA VIC_CONTROL_2 ; TURN ON MULTI COLOR MODE!
ORA #$10
STA VIC_CONTROL_2
LDA #$08
STA START_DELAY
LDA #$02
STA UPDATE_DELAY+1
LDA #$20
STA SPEED_DELAY
LDA #$C4
STA FUEL_IND
LDA #$30
STA FUELX
LDA #<FUELBURN
STA FUEL_DELAY
JSR DO_MOON_INDICATOR ; SHOW NUMBER OF MOONS TO LANDD
LDA #$10
STA RASTER ; SET INTERRUPT LINE
LDA #$81
STA IRQ_ENABLE ; ENABLE INTERRUPT
CLI
JSR INIT_ORBIT2
LDA #$04
STA VELOCITY
JSR DO_VELOCITY
LDA #$01
STA GAME_STATUS
STA READ_COLL_FLAG
LDA #<WHITE
STA SHIP_COLOR
LDA #$BE
STA SHIPY
LDA #$00
STA SHIPX+1
LDX #$18 ; INIT SHIP X,Y POSITIONS
_1 STX SHIPX
STX TEMP1
LDY #$00
_2 DEY ; SLIDE SHIP INTO SCENE FOR
BNE _2
LDX TEMP1 ; EFFECT!
INX
CPX #$A8
BNE _1
LDA #$01 ; SET SHIP COLOR TO WHITE!
STA REENTRY_COLOR
STA SHIP_COLOR
RTS
;--------------------------------
; INITS VARIABLES IN ORBIT SCENE
;--------------------------------
INIT_ORBIT2 LDA #$33 ; SETUP PROPER SHIP SHAPE
STA SHIP_PHASE
INC BANK_STAGE
JSR DO_BANK_INDICATOR ; INITALLY SHOW INDICATORS!
LDA #$00
STA KILL_FLAG
STA BANK_STAGE
RTS
;--------------------------------
; MOVE AND BANK SHIP
;--------------------------------
DO_SHIP JSR UPDATE_SHOT
LDA KILL_FLAG
BEQ _3
RTS
_3 LDX VELOCITY
LDA SHIP_DELAY
SEC
SBC VEL_SUB_TABLE,X
STA SHIP_DELAY
BCC _2
RTS
_2 LDA GAME_STATUS
CMP #$03
BNE _21
LDA #$0C
BNE _22
_21 LDA #$80
_22 STA SHIP_DELAY
LDA REENTRY_COLOR ; DO SHIPS COLOR
CMP #$01
BEQ _4
LDA #$01
STA SHIELD_ON_FLAG
DEC REENTRY_COLOR
LDA REENTRY_COLOR
AND #$0F
_4 STA SHIP_COLOR
JSR GETPORT
AND #$0C
CMP #$0C
BNE _1
JSR DO_STRAIGHTEN ; STRAIGHTEN SHIP IF NO MOVEMENT
_1 LDX #$00 ; OTHERWISE CHECK ALL MOVEMENT
JSR GETPORT ; AND JSR ACCORDINGLY
DO_SHIP_4 ROR
BCS DO_SHIP_3
PHA
TXA
PHA
LDA EXECUTION_TABLE,X
STA TEMP1
LDA EXECUTION_TABLE+1,X
STA TEMP2
LDA #>DO_SHIP_2-1
PHA
LDA #<DO_SHIP_2-1
PHA
JMP (TEMP1)
DO_SHIP_2 PLA
TAX
PLA
DO_SHIP_3 INX
INX
CPX #$0A
BNE DO_SHIP_4
JSR UPDATE_SHOT ; KEEP SHOT SPEED SAME
RTS
;--------------------------------
EXECUTION_TABLE .word DO_UP
.word DO_DOWN
.word DO_LEFT
.word DO_RIGHT
.word DO_SHOOT
;--------------------------------
; DO UP IF ON PLANET
;--------------------------------
DO_UP LDA GAME_STATUS ; ORBIT SCENE HAS NO GROUNDSPEED
CMP #$03
BNE _1
DEC SPEED_DELAY
BNE _1
LDA #$20
STA SPEED_DELAY
LDA GROUND_SPEED ; INC GROUNDSPEED IF NOT AT MAX
CMP #<MAXIMUM_SPEED
BEQ _1
INC GROUND_SPEED
_1 INC VEL_DELAY
LDA VEL_DELAY
CMP #$20
BNE _2
LDA #$00
STA VEL_DELAY
LDA VELOCITY ; INC VELOCITY IF NOT AT MAX
CMP #<MAXIMUM_VEL
BEQ _2
INC VELOCITY
JSR DO_VELOCITY ; UPDATE GUAGE
_2 RTS
;--------------------------------
; DO DOWN IF ON PLANET
;--------------------------------
DO_DOWN INC VEL_DELAY ; DEC VELOCITY IF NOT AT MIN
LDA VEL_DELAY
CMP #$20
BNE _2
LDA #$00
STA VEL_DELAY
LDA VELOCITY
CMP #<MINIMUM_VEL
BEQ _2
DEC VELOCITY
JSR DO_VELOCITY ; UPDATE GUAGE
_2 LDA GAME_STATUS ; IF IN ORBIT DO SHIELD
CMP #$03
BNE DO_SHIELD
DEC SPEED_DELAY
BNE _1
LDA #$20
STA SPEED_DELAY
LDA GROUND_SPEED ; DEC GROUNDSPEED IF NOT AT MIN
CMP #<MINIMUM_SPEED
BEQ _1
DEC GROUND_SPEED
LDA #$00
STA RING_SOUND_INDEX
_1 RTS
;--------------------------------
; TURNS ON SHIELD IF PULLING BACK
;--------------------------------
DO_SHIELD LDA SHIELD_DELAY
EOR #$01
STA SHIELD_DELAY
BNE _1
INC SHIELD_COLOR ; COLOR FOR SHIELD
LDA SHIELD_COLOR
CMP #$06 ; 6 COLORS FROM TABLE
BCC _1
LDA #$00
STA SHIELD_COLOR
_1 LDX SHIELD_COLOR
LDA COLORS_FOR_SHIELD,X
STA SHIP_COLOR
LDA #$01
STA SHIELD_ON_FLAG ; NO COLLISION DETECT!
STA BUZZ
RTS
;--------------------------------
COLORS_FOR_SHIELD .byte $02, $04, $07, $06, $05, $08
;--------------------------------
; MOVE SHIP LEFT AND BANK IT.
;--------------------------------
DO_LEFT LDA BANK_STAGE
BPL _11
JSR CONTINUE_SPEED ; KEEP GOING IN SAME DIRECTION
JMP _1
_11 LDA SHIPX+1 ; MSB
BNE _2
LDA SHIPX
CMP #$18 ; LEFT BOUNDARY
BEQ _1
_2 LDA SHIPX
SEC
SBC #$01
STA SHIPX ; MOVE LEFT ONE POSITION
BCS _1
LDA #$00
STA SHIPX+1 ; MSB
_1 LDA BANK_STAGE ; CHECK FOR BANK STAGE UPDATE
CMP #$18
BEQ _3
INC BANK_STAGE ; INC BANK STAGE
JSR CALC_SHIP_STAGE ; BANK SHIP IF NEEDED
_3 RTS
;--------------------------------
; MOVE SHIP RIGHT AND BANK IT.
;--------------------------------
DO_RIGHT LDA BANK_STAGE
BMI _11
JSR CONTINUE_SPEED ; KEEP GOING IN SAME DIRECTION
JMP _1
_11 LDA SHIPX+1 ; MSB
BEQ _2
LDA SHIPX
CMP #$48 ; RIGHT BOUNDARY
BEQ _1
_2 LDA SHIPX
CLC
ADC #$01 ; MOVE RIGHT ONE POSITION
STA SHIPX
BCC _1
LDA #$01
STA SHIPX+1 ; MSB
_1 LDA BANK_STAGE ; CHECK FOR BANK STAGE UPDATE
CMP #$E8
BEQ _3
DEC BANK_STAGE ; DEC BANK STAGE
JSR CALC_SHIP_STAGE ; BANK SHIP IF NEEDED
_3 RTS
;--------------------------------
; CONTINUE GOING IN SAME DIRECTION
; UNTIL BANK STAGE CHANGES
;--------------------------------
CONTINUE_SPEED LDA BANK_STAGE
BEQ _2 ; FIND CRUISING DIRECTION
BPL _1
LDA SHIPX+1 ; MSB
BEQ _3
LDA SHIPX
CMP #$48 ; RIGHT BOUNDARY
BEQ _2
_3 LDA SHIPX
CLC
ADC #$01 ; CONTINUE RIGHT MOVEMENT
STA SHIPX
BCC _5
LDA #$01
STA SHIPX+1 ; MSB
_5 RTS
_1 LDA SHIPX+1 ; MSB
BNE _4
LDA SHIPX
CMP #$18 ; LEFT BOUNDARY
BEQ _2
_4 LDA SHIPX
SEC
SBC #$01 ; CONTINUE LEFT MOVEMENT
STA SHIPX
BCS _2
LDA #$00
STA SHIPX+1 ; MSB
_2 RTS
;--------------------------------
; CALCULATES SHIP STAGE
;--------------------------------
CALC_SHIP_STAGE JSR DO_BANK_INDICATOR ; UPDATE GUAGE
LDA BANK_STAGE ; GET POSITION VALUE OF BANK
BEQ _6 ; LEFT,MIDDLE,OR RIGHT?
BPL _5
LDX #$03
_1 LDA RIGHT_TABLE-1,X ; CHECK WITH TABLE VALUES
CMP BANK_STAGE ; (-VALUE=RIGHT,+VALUE=LEFT)
BCC _2
BEQ _2
DEX
BNE _1
_2 TXA ; X CONTAINS VALUE TO ADD TO
STA TEMP1 ; SPRITE OFFSET
SEC
LDA #$37 ; SPRITE # OFFSET
SBC TEMP1
STA SHIP_PHASE ; UPDATE SHIP SPRITE
RTS
_5 LDX #$03
_3 LDA LEFT_TABLE-1,X ; CHECK WITH TABLE VALUES
CMP BANK_STAGE
BCC _4
BEQ _4
DEX
BNE _3
_4 TXA ; X CONTAINS VALUE TO SUBTRACT
_6 STA TEMP1
LDA #$33 ; SPRITE # OFFSET
SEC
SBC TEMP1
STA SHIP_PHASE ; UPDATE SHIP SPRITE
RTS
;--------------------------------
RIGHT_TABLE .byte $E8, $F0, $F8
LEFT_TABLE .byte $08, $10, $18
;--------------------------------
; STRAIGHTEN OUT SHIP
;--------------------------------
DO_STRAIGHTEN JSR CONTINUE_SPEED ; KEEP CRUISING
LDA BANK_STAGE ; GET BANK STAGE
BEQ _1 ; IF 0 THEN WE ARE STRAIGHT
BPL _2 ; +,-
INC BANK_STAGE ; INCREMENT TO BANK TOWARDS LEFT
JSR CALC_SHIP_STAGE ; UPDATE SPRITE
RTS
_2 DEC BANK_STAGE ; DECREMENT TO BANK TO RIGHT
JSR CALC_SHIP_STAGE ; UPDATE SPRITE
_1 RTS
;--------------------------------
; FIRE SHOT
;--------------------------------
DO_SHOOT LDA SHOT_STATUS
BEQ _1 ; IS THERE A SHOT ON SCREEN?
RTS
_1 LDA #$09
STA SHOT_TIME
STA SHOT_TIME_REP
LDA #<SHTSND
STA SHOT_SND
LDA GAME_STATUS
CMP #$01 ; IF IN ORBIT, ONLY SHOOT UP.
BNE _2
_5 LDA #$72
STA SHOT_POINTER ; SHOT UP PIC
LDA #$00
STA SHOT_XMOVER ; NO XMOVEMENT
LDA #$01
STA SHOT_XFLAG ; ONLY UPDATE YPOS
BNE _7
_2 JSR GETPORT ; READ JOYSTICK
ROR
ROR
BCS _3 ; IF UP, INCREASE Y MOVEMENT
PHA
LDA #$10
STA SHOT_TIME
STA SHOT_TIME_REP
LDA #$01
STA SHOT_UP_FLAG
PLA
_3 ROR
BCC _4 ; CHECK FOR LEFT
ROR
BCS _5 ; CHECK FOR RIGHT OR UP
_4 LDA SHIP_PHASE
SEC
SBC #$33 ; GET SHIP PHASE
BEQ _5
BCC _6
STA SHOT_XMOVER ; AMOUNT OF XMOVEMENT
LDA #$02
STA SHOT_XFLAG ; 1=MOVE RIGHT
LDA #$7B
STA SHOT_POINTER ; FIRST SHOT SHAPE RIGHT
BNE _7
_6 EOR #$FF ; GET ABSOLUTE VALUE
CLC
ADC #$01
STA SHOT_XMOVER ; AMOUNT OF XMOVEMENT
LDA #$00
STA SHOT_XFLAG ; 0=MOVE LEFT
LDA #$6B
STA SHOT_POINTER ; FIRST SHOT SHAPE LEFT
_7 LDA SHOT_XMOVER
CMP #$03
BEQ _8
LDA #$73
STA SHOT_POINTER
_8 LDA SHIPX ; XPOS OF SHOT
STA SHOTX
LDA SHIPX+1 ; MSB
STA SHOTX+1
LDA #$B0 ; YPOS OF SHOT
STA SHOTY
LDA #<ORANGE
STA SHOT_COLOR
LDA #$01
STA SHOT_STATUS
LDA GAME_STATUS
CMP #$03
BNE _9
LDA #$06
BNE _10
_9 LDA #<SHOT_SPEED
_10 STA SHOT_DELAY
RTS
;--------------------------------
; UPDATE SHOT POINTERS
;--------------------------------
UPDATE_SHOT DEC SHOT_DELAY
BNE _1
LDA GAME_STATUS
CMP #$03
BNE _7
LDA #$06
BNE _8
_7 LDA #<SHOT_SPEED
_8 STA SHOT_DELAY ; CONTROL SPEED TO MAKE UNIFORM
LDA SHOT_STATUS
BEQ _1
DEC SHOTY ; MOVE UP SCREEN
LDA SHOT_XFLAG ; LEFT OR RIGHT
BNE _2
LDA SHOTX
SEC
SBC SHOT_XMOVER ; MOVE LEFT
STA SHOTX
BCS _3
LDA #$00
STA SHOTX+1
_3 LDA SHOTX+1 ; CHECK XPOS IF OFF SCREEN
BNE _4
LDA SHOTX
CMP #$08
BCS _4
BCC _5
_2 CMP #$01 ; IF UP DON'T MOVE XPOS
BEQ _4
LDA SHOTX
CLC
ADC SHOT_XMOVER ; MOVE RIGHT
STA SHOTX
BCC _6
LDA #$01
STA SHOTX+1
_6 LDA SHOTX+1 ; CHECK XPOS IF OFF SCREEN
BEQ _4
LDA SHOTX
CMP #$58
BCC _4
BCS _5
_4 DEC SHOT_TIME
BNE _1
LDA SHOT_TIME_REP
STA SHOT_TIME
INC SHOT_POINTER
INC SHOT_COUNT
LDA SHOT_COUNT
CMP #$07 ; CHECK FOR LAST PIC
BNE _1
_5 LDA #$00
STA SHOT_STATUS ; CHECK FOR ANOTHER BUTTON PRESS
STA SHOTY
STA SHOT_COUNT
_1 RTS ; SHOT NOT DONE, WAIT TILL IT IS
;--------------------------------
; SETS VALUE FOR BANK INDICATOR
;--------------------------------
DO_BANK_INDICATOR LDA BANK_STAGE ; GET BANK STAGE
BEQ _1 ; IF 0 THEN CENTER GUAGE
BPL _2 ; GREATER THAN 0
EOR #$FF ; GET ABSOLUTE VALUE
CLC
ADC #$01
LSR ; DIVIDE BY 2
LSR
STA TEMP1
LDA #$68
CLC
ADC TEMP1 ; MOVE TO RIGHT
STA BANKX ; XPOS OF BANK INDICATOR SPRITE
RTS
_2 LSR
LSR
STA TEMP1
LDA #$68
SEC
SBC TEMP1 ; MOVE TO LEFT
STA BANKX
_1 RTS
;--------------------------------
; MOVES VELOCITY DIAL
;--------------------------------
DO_VELOCITY LDA VELOCITY ; GET VELOCITY
CMP #$08 ; VEL. = 0 TO 15 SO 8 IS MIDDLE
BEQ _2 ; CENTER GUAGE
BCC _3 ; LESS THAN
SEC
SBC #$08 ; GET AMOUNT FROM MIDDLE (8)
PHA
CLC
ADC #$42 ; XPOS OF GUAGE SPRITE
STA VELX
PLA
CLC
ADC #$BD
STA VEL_IND ; UPDATE SPRITE PIC
RTS
_3 PHA
CLC
ADC #$2E ; XPOS OF GUAGE
STA VELX
PLA
CLC
ADC #$B5 ; UPDATE SPRITE
STA VEL_IND
RTS
_2 LDA #$BD
STA VEL_IND ; MIDDLE PIC
LDA #$38 ; MIDDLE XPOS
STA VELX
RTS
;--------------------------------
; DETERMINES AMOUNT OF FUEL
;--------------------------------
DO_FUEL LDA KILL_FLAG ; IN EXPLOSION SEQUENCE=1
BEQ _13
RTS
_13 DEC FUEL_DELAY ; DELAY FOR GUAGE
BNE _45
LDA GAME_STATUS
CMP #$03
BNE _8
LDA #$06
BNE _9
_8 LDA #<FUELBURN ; RESET
_9 STA FUEL_DELAY
LDA GAME_STATUS
CMP #$03
BEQ _2
LDA SHIELD_ON_FLAG ; IF SHIELD ON DEC MORE
BNE _2
LDA FUEL
SEC
SBC #$01 ; FUEL=FUEL-1
STA FUEL
BCS _1
_4 LDA FUEL_IND
CMP #$BA ; USED TO MOVE GUAGE SMOOTHLY
BNE _7
INC FUEL_LOW_FLAG
BNE _12
_7 CMP #$BE ; MIDDLE POSITION
BEQ _3
CMP #$BD
BNE _5
LDA #$1F
STA FUELX
BNE _5
_3 LDA #$21
STA FUELX
_5 DEC FUELX
_12 DEC FUEL_IND ; UPDATE SPRITE
LDA FUEL_IND
CMP #$B6 ; OUT OF FUEL?
_45 BNE _1
LDA #$37
STA SHIP_PHASE ; FIRST EXPLOSION PIC
LDA #$01
STA KILL_FLAG ; INIT BLOW UP ROUTINES
STA SHIP_COLOR ; WHITE
LDA #$00
STA FUEL_LOW_FLAG
LDA #$C4
STA FUEL_IND
LDA #$30
STA FUELX
LDA #$10
STA BLOW_UP_DELAY
LDA #$01
BNE _11
LDA #<DEATH_SPEED
_11 STA BLOW_UP_DELAY+1 ; DELAY FOR EXPLOSION
LDA #<BLPSND
STA BLOWUP_SND
SEI
LDA #<BLOWUP_SOUND_TBL
STA NOTE_POINTER
LDA #>BLOWUP_SOUND_TBL
STA NOTE_POINTER+1
LDA #$01
STA NOTE_DELAY
CLI
JMP BLOW_UP_SHIP ; START BLOW UP
_1 RTS
;--------------------------------
_2 LDA REENTRY_COLOR
CMP #$01
BNE _1
JSR GETPORT ; READ STICKS
AND #$02 ; SHIELD STILL ON!
BEQ _6
LDA #$00
STA SHIELD_ON_FLAG
STA BUZZ
_6 LDA FUEL
SEC
SBC #<SHIELDBURN ; FASTER FUEL DEC
STA FUEL
BCS _1
BCC _4
;--------------------------------
; KILL SHIP AND SUBTRACT LIFE
;--------------------------------
BLOW_UP_SHIP LDA KILL_FLAG ; ARE WE IN KILL SEQUENCE
BEQ _1
DEC BLOW_UP_DELAY
BNE _1
DEC BLOW_UP_DELAY+1
BNE _1
LDA GAME_STATUS
CMP #$03
BNE _3
LDA #$08
STA BLOW_UP_DELAY
LDA #$01
BNE _4
_3 LDA #<DEATH_SPEED ; RESET
_4 STA BLOW_UP_DELAY+1
INC SHIP_COLOR
INC SHIP_PHASE ; UPDATE SPRITE
LDA SHIP_PHASE
CMP #$3E ; DONE?
BNE _1
DEC LIVES ; UPDATE LIVES
LDA LIVES
JSR DO_LIVES
LDA LIVES
BNE _2
LDA #$00
LDY #$04
_6 STA YSPRITE,Y
DEY
BPL _6
_7 LDA VIC_CONTROL_1
BPL _7
_8 LDA VIC_CONTROL_1
BMI _8
LDA GAME_STATUS
CMP #$03
BNE _5
JMP TAKE_OFF_MOON
_5 JMP GAME_OVER ; IF 0 THEN GAME OVER
_2 JSR INIT_ORBIT2 ; PUT SHIP BACK ON
LDA #$FF
STA REENTRY_COLOR ; SHIELD ON WHEN SHIP APPEARS
LDA #$01
STA SHIELD_ON_FLAG
_1 RTS
