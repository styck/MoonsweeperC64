; DETECTS PLANET SPRITE COLLISIONS
;--------------------------------
PLANET_COLLISIONS LDA KILL_FLAG
BNE _01 ; IF EXPLODING, SKIP SHIP CHECK
JSR DO_SHIP_COLLISIONS ; UPDATE SHIP COLLISIONS
_01 JSR DO_SHOT_COLLISIONS ; UPDATE SHOT COLLISIONS
RTS
;--------------------------------
; CHECKS FOR SHIP COLLISIONS
;--------------------------------
DO_SHIP_COLLISIONS LDA SHIP_COLLIDE ; GET COLLISION DATA
ROR
ROR
ROR
LDY #$FF
_02 INY
CPY #$05
BEQ _01
ROR
BCC _02
PHA
TYA
TAX
PLA
_68 INY
CPY #$05
BEQ _67
ROR
BCC _68
BCS _01
_67 LDA CRATER_FLAG,X
BNE _01
LDA OBJECT_TYPE,X ; GET TYPE OF OBJECT
CMP #$0B
BEQ _01
CMP #$0C
BEQ _01
CMP #$08 ; CHECK FOR A MAN
BNE _03
LDA #$01
STA SCORE_TEMP+1
LDA #$00
STA YSPRITE,X
STA SPRITE_STATUS,X ; TAKE MAN OFF SCREEN
STA SPRITE_WHOLE,X
STA SCORE_TEMP
STA SCORE_TEMP+2
SEI
LDA #<MAN_SOUND_TBL-4
STA NOTE_POINTER
LDA #>MAN_SOUND_TBL-4
STA NOTE_POINTER+1
LDA #$01
STA NOTE_DELAY
CLI
LDA TEMP1
PHA
JSR DO_SCORE_ADD
JSR DO_MEN_PICKED_UP ; UPDATE MEN ON SCREEN
PLA
STA TEMP1
_01 RTS
_03 CMP #$0A ; CHECK FOR A RING
BNE _04
LDA XSPRITE,X
CLC
ADC #$0B
STA TEMP7
LDA XMSB_SPRITE,X ; TEMP 7,8 IS SPRITE XPOS +4
ADC #$00
STA TEMP8
LDA TEMP7 ; NOW SUBTRACT SHIPS XPOS!
SEC
SBC SHIPX
STA TEMP7
LDA TEMP8
SBC SHIPX+1
BNE _01
LDA TEMP7
CMP #$12
BCS _01
DEC RING_DELAY
BNE _01
LDA #$06
STA RING_DELAY
LDY RING_SOUND_INDEX
CPY #$20
BNE _31
LDY #$1C
STY RING_SOUND_INDEX
_31 LDA RING_FRQ_TBL,Y
STA RING_SOUND_TBL
INY
LDA RING_FRQ_TBL,Y
STA RING_SOUND_TBL+1
INY
STY RING_SOUND_INDEX
SEI
LDA #<RING_SOUND_TBL-4
STA NOTE_POINTER
LDA #>RING_SOUND_TBL-4
STA NOTE_POINTER+1
LDA #$01
STA NOTE_DELAY
CLI
INC RING_COUNT
LDA VELOCITY
CMP #<MAXIMUM_VEL
BEQ _05
CLC
ADC #$01
STA VELOCITY
JSR DO_VELOCITY
_05 LDA GROUND_SPEED
CMP #<MAXIMUM_SPEED
BEQ _06
CLC
ADC #$02
STA GROUND_SPEED ; ADD TWO TO GROUND.SPEED
_06 LDA RING_COUNT
CMP #$05
BCC _01
LDA GROUND_SPEED
CMP #<MAXIMUM_SPEED
BCC _07
JMP TAKE_OFF_MOON ; IF OVER MAX, LEAVE MOON
_07 RTS
_04 LDA SHIELD_ON_FLAG
BNE _07
LDA #$10
STA BLOW_UP_DELAY
LDA #$01
STA BLOW_UP_DELAY+1 ; RESET BLOWUP DELAY
STA KILL_FLAG ; START BLOWUP SEQUENCE
LDA #<YELLOW
STA SHIP_COLOR ; CHANGE SHIP COLOR
LDA #$37
STA SHIP_PHASE ; FIRST BLOWUP SHAPE
LDA #<BLPSND
STA BLOWUP_SND
SEI
LDA #<BLOWUP_SOUND_TBL
STA NOTE_POINTER
LDA #>BLOWUP_SOUND_TBL
STA NOTE_POINTER+1
LDA #$01
STA NOTE_DELAY
CLI
RTS
;--------------------------------
; RING NOTE FREQUENCIES
;---------------------------------
RING_FRQ_TBL .byte $1F, $90, $20, $90, $21, $90, $22, $90
.byte $23, $90, $24, $90, $25, $90, $26, $90
.byte $27, $90, $28, $90, $29, $90, $2A, $90
.byte $2B, $90, $2C, $90, $2D, $90, $2E, $90
;--------------------------------
; CHECK IF SHOT HIT AN OBJECT
;--------------------------------
DO_SHOT_COLLISIONS LDA MID_COLLIDE ; GET COLLISION DATA
STA TEMP1
ROR
ROR
BCS _11 ; CHECK IF OBJECT HIT
_12 RTS
_11 LDA TEMP1
ROR
BCS _12 ; CHECK IF A SAUCER
ROR ; SKIP TO LAST 5 BITS
ROR
BCS _12 ; CHECK OTHER SAUCER
LDX #$FF
_02 ROR
INX
BCC _02 ; GET OBJECT HIT
LDA CRATER_FLAG,X
BNE _12
LDA OBJECT_TYPE,X ; GET TYPE OF OBJECT HIT
CMP #$09
BEQ _12 ; SKIP A CRATER
CMP #$0A
BEQ _01 ; SKIP A RING
CMP #$0B
BEQ _01
CMP #$0C
BEQ _01
CMP #$0D
BEQ _01
LDY #$00
STY SCNTRL_2
STY SHOTY
STY SHOT_STATUS ; TAKE SHOT OFF SCREEN
STY SHOT_COUNT
INY
STY EXPLODE_FLAG,X ; START EXPLODING OBJECT
LDY #<BLPSND
STY BLOWUP_SND
LDY #$0B
STY OBJECT_TYPE,X
CMP #$08
BEQ _01
STA TEMP1
CMP #$06
BNE _03 ; CHECK FOR TOWER TOP
LDY #$0C
STY OBJECT_TYPE,X
INC TEMP1 ; POINT TO TOWER TOP
BNE _04
_03 DEC TEMP1 ; POINT TO TOWER BOTTOM
_04 LDY #$04
_06 LDA OBJECT_TYPE,Y
CMP TEMP1
BEQ _05 ; FIND OTHER HALF OF TOWER
_07 DEY
BPL _06
_05 LDA XSPRITE,Y
CMP XSPRITE,X
BNE _07 ; CHECK IF AT SAME XPOS
LDA YSPRITE,Y
SEC
SBC YSPRITE,X
BPL _08
EOR #$FF
CLC
ADC #$01
_08 CMP #$20
BCS _07
LDA #$01
STA EXPLODE_FLAG,Y ; START EXPLODING OTHER HALF
LDA OBJECT_TYPE,Y
CMP #$06
BNE _09
LDA #$0C
BNE _10
_09 LDA #$0B
_10 STA OBJECT_TYPE,Y
LDA #$50
STA SCORE_TEMP
LDA #$00
STA SCORE_TEMP+1
STA SCORE_TEMP+2
JSR DO_SCORE_ADD
_01 RTS
