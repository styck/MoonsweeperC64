LDA SPRITE_FRACTION,X
STA TEMP3 ; FRAC FOR CALC.NEW.HEIGHT
JSR CALC_NEW_HEIGHT ; CALC NEW HEIGHT OFFSET
LDA TEMP3 ; GET NEW FRACTION
STA SPRITE_FRACTION,X ; RESTORE NEW FRACTION
LDA TEMP4 ; GET OFFSET
STA SPRITE_WHOLE,X ; SAVE FOR NEXT TIME
