;--------------------------------
; 16 BY 16 UNSIGNED DIVISION:
; DIVIDEND=TEMP1(LOW),TEMP2(HI)
; DIVISOR =TEMP3(LOW),TEMP4(HI)
; QUOTIENT=REPLACES THE DIVIDEND
; REMAINDER=TEMP5(LOW),TEMP6(HI)
; DESTROYS X,Y,A
;--------------------------------
DIVIDER LDA #$00 ; CLEAR PARTIAL DIVIDEND
STA TEMP5
STA TEMP6
LDX #$10
NEXT_BIT ASL TEMP1
ROL TEMP2
ROL TEMP5 ; SHIFT PARTIAL DIVIDEND LEFT
ROL TEMP6
LDA TEMP5 ; SUBTRACT LOW BYTES
SEC
SBC TEMP3
TAY ; SAVE LOW RESULT IN Y
LDA TEMP6 ; SUBTRACT HIGH BYTES
SBC TEMP4
BCC CNTDN ; DIVISOR>DIVIDEND?
INC TEMP1 ; NO. SET BIT IN QUOTIENT
STA TEMP6 ; AND ENTER SUBTRACTION RESULT
TYA
STA TEMP5 ; INTO PARTIAL DIVIDEND.
CNTDN DEX ; BIT COUNT=COUNT-1
BNE NEXT_BIT ; LOOP UNTIL 16 BITS ARE DONE.
RTS
