;--------------------------------
; UPDATES MOTHER SHIP OR SATELLITE
;--------------------------------
DO_MOTHER_SHIP LDA MOTHER_STATUS
BNE _01
DEC MOTHER_DELAY
BNE _02
JSR SETUP_MOTHER ; INIT MOTHER OR SATELLITE
JSR SETUP_XPOS_START ; SETUP STARTING XPOS
_01 JSR MOTHER_COLLISION ; CHECK IF HIT
JSR MOTHER_XMOVER ; MOVE LEFT OR RIGHT
JSR MOTHER_DONE_CHECK ; CHECK IF WE ARE DONE
LDA MOTHER_PATH ; GET TYPE OF YMOVEMENT
BEQ _02 ; JUMP TO PROPER SUBROUTINE
CMP #$01
BEQ _03
JSR MOTHER_Y2
RTS
_03 JSR MOTHER_Y1
_02 RTS
;--------------------------------
; INITIALIZES MOTHER SHIP
;--------------------------------
SETUP_MOTHER LDX PLANET_COLOR
LDA ISSUE_TIMER,X
STA MOTHER_DELAY ; SETUP DELAY UNTIL NEXT MOTHER
LDA MOTHER_DIR
EOR #$01
STA MOTHER_DIR
LDA #$01
STA MOTHER_STATUS
LDA #$40
STA MOTHERY
STA MOTHERY+1
STA MOTHERY+2
LDA #$00
STA STOP_MOVE_FLAG
STA STOP_MOVE_FLAG+1
STA STOP_MOVE_FLAG+2
LDA SATELLITE_PROB,X ; CHECK FOR A SATELLITE
SEC
SBC RANDOM_NUMBER
BCS _01
LDA #$B2 ; INIT MOTHER
STA MOTHER_SPRITE
LDA #$B3
STA MOTHER_SPRITE+1
LDA #$CA
STA MOTHER_SPRITE+2
LDA RANDOM_NUMBER
AND #$03
STA MOTHER_PATH
LDA #$00
STA SATELLITE_FLAG
LDA #$01
STA MOTHER_FLAG
RTS
_01 LDA #$3E ; INIT SATELLITE
STA MOTHER_SPRITE
LDA #$92
STA MOTHER_SPRITE+1
LDA #$CA
STA MOTHER_SPRITE+2
LDA #$01
STA SATELLITE_FLAG
LDA #$00
STA MOTHER_PATH
STA MOTHER_FLAG
RTS
;--------------------------------
; SETS UP STARTING XPOS OF SPRITES
;--------------------------------
SETUP_XPOS_START LDA MOTHER_DIR ; SETUP MOTHER STARTING XPOS
BNE _01 ; ACCORDING TO MOVE DIRECTION
LDA #$00
LDX #$02
_02 STA MOTHERX,X
STA MOTHERXMSB,X
DEX
BPL _02
RTS
_01 LDX #$02
_03 LDA #$01
STA MOTHERXMSB,X
LDA #$58
STA MOTHERX,X
DEX
BPL _03
RTS
;--------------------------------
; TABLES FOR DIFFICULTY
;--------------------------------
SATELLITE_PROB .byte $00, $00, $10, $00, $00, $50, $6E, $20
ISSUE_TIMER .byte $00, $00, $40, $00, $00, $C8, $FA, $50
SAUCER_VEL_TBL .byte $00, $00, $0F, $00, $00, $07, $03, $0B
;--------------------------------
; MOTHER PATH FORMULAS
;--------------------------------
MOTHER_DONE_CHECK LDA MOTHER_DIR ; MOVING LEFT OR RIGHT?
BNE _01 ; 0=RIGHT
LDY #$02
_05 LDX MOTHER_SPRITES_R,Y
LDA STOP_MOVE_FLAG,X
BNE _03
LDA MOTHERXMSB,X
BEQ _02
LDA MOTHERX,X
CMP #$58
BNE _03
LDA #$00
STA MOTHERY,X
LDA #$01
STA STOP_MOVE_FLAG,X
LDA SATELLITE_FLAG ; IF SATELLITE, THEN END IT
BNE _04 ; DON'T END MOTHER UNTIL ALL
DEY ; SPRITES ARE OFF SCREEN
BMI _04
RTS
_03 DEY
BPL _05
_02 RTS
_01 LDY #$02
_08 LDX MOTHER_SPRITES_L,Y ; MOTHER MUST SCROLL OFF SMOOTH
LDA STOP_MOVE_FLAG,X
BNE _06
LDA MOTHERXMSB,X ; SO DON'T END TILL OFF SCREEN
BNE _02
LDA MOTHERX,X
BNE _06
LDA #$00
STA MOTHERY,X
LDA #$01
STA STOP_MOVE_FLAG,X
LDA SATELLITE_FLAG ; IF SATELLITE, THEN END IT
BNE _04
DEY
BMI _04
RTS
_06 DEY
BPL _08
RTS
_04 LDA #$00 ; DONE, SO BUILD ANOTHER MOTHER
STA MOTHER_STATUS
RTS
;--------------------------------
MOTHER_XMOVER LDA MOTHER_DIR ; MOVE LEFT OR RIGHT?
BNE _01 ; 0=RIGHT
LDY #$02
_03 LDX MOTHER_SPRITES_R,Y
LDA STOP_MOVE_FLAG,X
BNE _02
LDA MOTHERX,X
CLC
ADC #$01 ; MOVE MOTHER SPRITES RIGHT
STA MOTHERX,X
BCC _02
LDA #$01
STA MOTHERXMSB,X
_02 JSR CHECK_ISSUE ; IF STARTING OUT FROM EDGE,
DEY ; ADJUST SPRITES SO THEY COME
BPL _03 ; OUT IN SEQUENTIAL ORDER
RTS
_01 LDY #$02
_05 LDX MOTHER_SPRITES_L,Y
LDA STOP_MOVE_FLAG,X
BNE _04
LDA MOTHERX,X
SEC
SBC #$01 ; MOVE MOTHER SPRITES LEFT
STA MOTHERX,X
BCS _04
LDA #$00
STA MOTHERXMSB,X
_04 JSR CHECK_ISSUE ; START FROM EDGE IN ORDER
DEY
BPL _05
RTS
;--------------------------------
MOTHER_Y1 LDA MOTHER_MOVE_FLAG ; DELAY
EOR #$01
STA MOTHER_MOVE_FLAG
BNE _13
LDX #$02
_10 LDA STOP_MOVE_FLAG,X
BNE _15
LDA MOTHERY,X
CMP #$38 ; CHECK TOP OF SINE WAVE
BEQ _01 ; IF THERE, MOVE DOWN
_15 DEX ; CHECK ALL SPRITES, SINCE SOME
BPL _10 ; MAY BE OFF OF SCREEN
LDX #$02
_11 LDA STOP_MOVE_FLAG,X
BNE _16
LDA MOTHERY,X
CMP #$48 ; CHECK BOTTOM OF SINE WAVE
BEQ _01
_16 DEX
BPL _11
LDX #$02
_03 LDA SINE_Y ; CHECK IF UP OR DOWN
BNE _02 ; 0=UP
_12 LDA STOP_MOVE_FLAG,X
BNE _14
DEC MOTHERY,X ; MOVE MOTHER SPRITES UP
_14 DEX
BPL _12
_13 RTS
_02 INC MOTHERY,X ; MOVE MOTHER SPRITES DOWN
DEX
BPL _02
RTS
_01 LDA SINE_Y
EOR #$01 ; CHANGE DIRECTION
STA SINE_Y
LDX #$02
JMP _03
;--------------------------------
MOTHER_Y2 LDA MOTHER_DIR ; LEFT OR RIGHT?
BNE _01
LDA MOTHERX+1
CMP #$B0 ; CHECK FOR MIDDLE OF SCREEN
BCC _02
CMP #$D0 ; CHECK IF MOTHER OFF SCREEN
BNE _03
LDA #$00
STA MOTHER_STATUS ; BUILD NEW MOTHER
_03 LDX #$02
_04 DEC MOTHERY,X ; MOVE MOTHER UP
DEX
BPL _04
_02 RTS
_01 LDA MOTHERXMSB ; MOVING LEFT
BNE _02
LDA MOTHERX
CMP #$B0 ; CHECK FOR MIDDLE
BCS _02
CMP #$90 ; CHECK IF MOTHER OFF SCREEN
BNE _03
LDA #$00
STA MOTHER_STATUS ; IF SO, BUILD NEW MOTHER
JMP _03 ; OTHERWISE, MOVE UP
;--------------------------------
; IF MOTHER, CONTROL ISSUE OF SPRITES
;--------------------------------
CHECK_ISSUE LDA SATELLITE_FLAG ; CHECK IF A SATELLITE
BNE _01
LDA MOTHER_DIR ; LEFT OR RIGHT?
BNE _02 ; 0=RIGHT
LDX MOTHER_SPRITES_R,Y
LDA MOTHERXMSB,X
BNE _01 ; IF XMSB SET, THEN NOT AT EDGE
LDA MOTHERX,X
CMP #$09 ; ISSUE SPRITE EVERY 8 POSITIONS
BCS _01
_03 PLA ; PULL RETURN ADDRESS, SO OTHER
PLA ; SPRITES WON'T MOVE OUT
_01 RTS
_02 LDX MOTHER_SPRITES_L,Y ; IF HERE, MOVING LEFT
LDA MOTHERXMSB,X
BEQ _01 ; IF XMSB CLEAR, NOT AT EDGE
LDA MOTHERX,X
CMP #$50 ; EDGE AT $48, ISSUE EVERY 8 POS
BCC _01 ; IF <, MOVE OTHER SPRITES
JMP _03 ; OTHERWISE, PULL RETURN ADDRESS
;--------------------------------
; CHECKS FOR MOTHER KILL
;--------------------------------
MOTHER_COLLISION LDA MOTHER_KILL_FLAG ; ALREADY EXPLODING?
BNE _04
LDA TOP_COLLIDE ; GET COLLISION DATA
LDY #$00
STY TOP_COLLIDE
ROR
ROR
BCC _01 ; IS SHOT HIT?
ROR
ROR
ROR
LDX #$03
_03 ROR
BCS _02
DEX
BNE _03
RTS
_02 LDA #$01
STA MOTHER_KILL_FLAG ; START MOTHER KILL SEQUENCE
LDA #<BLPSND
STA BLOWUP_SND
LDA #$00
STA MOTHER_FLAG ; SO SAUCER WON'T DROP
PLA ; PULL RETURN ADDRESS, STOP MOV.
PLA
_01 RTS
_04 LDA MOTHER_KILL_COUNT ; COUNTS EXPLOSION PICS
BNE _05
LDA SATELLITE_FLAG ; IF SATELLITE MOVE FRONT SPRITE
BEQ _08
LDA #$00
STA MOTHERY+1
JMP _05
_08 LDA MOTHERX+1
CLC
ADC #$10 ; SPLIT MOTHER INTO THREE PARTS
STA MOTHERX+1
BCC _06
LDA #$01
STA MOTHERXMSB+1
_06 LDA MOTHERX
SEC
SBC #$10
STA MOTHERX
BCS _05
LDA #$00
STA MOTHERXMSB
_05 LDX MOTHER_KILL_COUNT ; GET EXPLOSION PIC INDEX
CPX #$05
BEQ _07
LDA MOTHER_EXPLOSION,X ; GET EXPLOSION PIC
STA MOTHER_SPRITE ; UPDATE SPRITES
STA MOTHER_SPRITE+1
STA MOTHER_SPRITE+2
INC MOTHER_KILL_COUNT ; POINT TO NEXT PIC
PLA ; DON'T MOVE MOTHER
PLA
RTS
_07 LDA #$00 ; 0 ALL FLAGS FOR REBUILDING
STA MOTHER_KILL_COUNT ; AND PULL SPRITES OFF SCREEN
STA MOTHER_KILL_FLAG
STA MOTHER_STATUS
STA MOTHERY
STA MOTHERY+1
STA MOTHERY+2
STA SCORE_TEMP ; WORTH 200 POINTS
STA SCORE_TEMP+2
LDA #$02
STA SCORE_TEMP+1
JSR DO_SCORE_ADD
PLA ; DON'T MOVE!
PLA
RTS
;--------------------------------
; TABLE FOR MOTHER EXPLOSION
;--------------------------------
MOTHER_EXPLOSION .byte $C8, $3B, $C6, $3C, $3D
;--------------------------------
; INDEX TABLE
;--------------------------------
MOTHER_SPRITES_R .byte $00, $02, $01
MOTHER_SPRITES_L .byte $01, $02, $00
;--------------------------------
; UPDATES SAUCER
;--------------------------------
DO_SAUCER DEC SAUCER_DELAY ; DELAY FOR SAUCER ISSUE
BNE _01
LDA SAUCER_COUNT ; MAX OF 2 ON SCREEN AT ONE TIME
CMP #$02
BEQ _01
LDA MOTHER_FLAG ; CHECK IF MOTHER ON SCREEN
BEQ _01
LDA MOTHERY+2 ; MAKE SURE MOTHER IS OFF EDGE
CMP #$30
BCC _01
LDA MOTHERXMSB+2
BNE _04
LDA MOTHERX+2
CMP #$18
BCC _01
BCS _05
_04 LDA MOTHERX+2
CMP #$48
BCS _01
_05 LDX #$01 ; INDEX FOR SAUCERS
_03 LDA SAUCER_STATUS,X ; IS SAUCER ALREADY ON SCREEN?
BNE _02
INC SAUCER_STATUS,X ; NO, SO BUILD ONE. FLAG ON!
LDA #$00
STA SAUCER_INDEX,X ; 0 INDEX AND FRACTIONS
STA SAUCER_XFRAC,X
STA SAUCER_YFRAC,X
LDA RANDOM_NUMBER ; GET A RANDOM XVELOCITY
AND #$3F
CLC
ADC #$60
STA SAUCER_XVEL,X
LDA #$96 ; SET UP STARTING YVELOCITY
STA SAUCER_YVEL,X
JSR SAUCER_INIT ; GET STARTING POSITIONS
LDA TEMP1 ; UPDATE POSITION VARIABLES
STA SAUCER_SPRITE,X
LDA TEMP2
STA SAUCERX,X
LDA TEMP3
STA SAUCERXMSB,X
LDA TEMP4
STA SAUCERY,X
JMP _01 ; DON'T ISSUE NEXT SAUCER
_02 DEX ; CHECK NEXT SAUCER
BPL _03
_01 JSR MOVE_SAUCER ; MOVE SAUCERS
JSR SAUCER_COLLISION ; CHECK FOR COLLISIONS
RTS
;--------------------------------
; TEMP1=SAUCER.SPRITE TEMP4=SAUCERYPOS
; TEMP2=SAUCERXPOS
; TEMP3=SAUCERXMSB    ALL ON EXIT....
;--------------------------------
SAUCER_INIT INC SAUCER_COUNT ; MAX OF TWO ON SCREEN
LDY #$00
LDA SAUCER_DROP,Y ; GET FIRST DROPPING PICTURE
STA TEMP1
LDA MOTHERX+2 ; DROP FROM MIDDLE MOTHER SPRITE
STA TEMP2
LDA MOTHERXMSB+2
STA TEMP3
LDA MOTHERY+2
CLC
ADC #$10 ; DROP FROM BELOW MOTHER
STA TEMP4
RTS
;--------------------------------
; MOVES SAUCER1
;--------------------------------
MOVE_SAUCER LDX #$01
_07 LDA SAUCER_STATUS,X ; CHECK IF SAUCER ON SCREEN
BNE _01
_03 JMP _02
_01 LDA SAUCER_KILL_FLAG,X
BNE _03
LDA SAUCERY,X ; CHECK IF STILL DROPPING
CMP #$68
BCS _04
LDA SAUCER_UP_DELAY,X
EOR #$01
STA SAUCER_UP_DELAY,X
BNE _03
INC SAUCERY,X ; MOVE DOWN ONE POSITION
INC SAUCER_INDEX,X ; INC PICTURE INDEX
LDY SAUCER_INDEX,X
CPY #$03 ; CHECK IF END OF TABLE
BNE _05
LDA #$00 ; IF SO, MOVE TO BEGINNING
STA SAUCER_INDEX,X
TAY
_05 LDA SAUCER_DROP,Y ; GET NEW PICTURE
STA SAUCER_SPRITE,X ; UPDATE SPRITE
RTS
_04 LDA SAUCER_XVEL,X ; SENDS PARAMETERS TO SUBROUTINE
STA TEMP1 ; AND UPDATES NEW VALUES........
LDA SAUCER_YVEL,X
STA TEMP2
LDA SAUCERX,X
STA TEMP3
LDA SAUCERXMSB,X
STA TEMP4
LDA SAUCERY,X
STA TEMP5
JSR SAUCER_MOVER
LDA TEMP1
STA SAUCER_XVEL,X
LDA TEMP2
STA SAUCER_YVEL,X
LDA SAUCERX,X
STA TEMP2
LDA SAUCERXMSB,X
STA TEMP3
LDA SAUCER_XFRAC,X
STA TEMP4
JSR CALC_SAUCER_POS
LDA TEMP2
STA SAUCERX,X
LDA TEMP3
STA SAUCERXMSB,X
LDA TEMP4
STA SAUCER_XFRAC,X
LDA SAUCER_YVEL,X
STA TEMP1
LDA SAUCERY,X
STA TEMP2
LDA #$00
STA TEMP3
LDA SAUCER_YFRAC,X
STA TEMP4
JSR CALC_SAUCER_POS
LDA TEMP2
STA SAUCERY,X
LDA TEMP4
STA SAUCER_YFRAC,X
LDA SAUCERX,X
STA TEMP3
LDA SAUCERXMSB,X
STA TEMP4
LDA SAUCERY,X
STA TEMP5
JSR CHECK_BORDERS
LDA TEMP3
STA SAUCERX,X
LDA TEMP5
STA SAUCERY,X
STA TEMP1
JSR UPDATE_SAUCER
LDY TEMP2
LDA SAUCER_PIC_TABLE,Y
STA SAUCER_SPRITE,X
_02 DEX
BMI _06
JMP _07
_06 RTS
;--------------------------------
; TEMP1=SAUCERXVEL   THIS ROUTINE
; TEMP2=SAUCERYVEL   MOVES THE
; TEMP3=SAUCERXPOS   SAUCER.....
; TEMP4=SAUCERXMSB
; TEMP5=SAUCERYPOS
;--------------------------------
SAUCER_MOVER LDY PLANET_COLOR
LDA SAUCER_VEL_TBL,Y
STA TEMP8 ; FINDS OFFSET VALUE FOR VEL
LDA TEMP4 ; CHECK XMSB
CMP OLDSHIPX+1
BNE _01
LDA TEMP3 ; ADD OR SUBTRACT FROM VELOCITY
CMP OLDSHIPX ; TO AIM TOWARDS THE SHIP'S OLD
BCC _02 ; XPOS.......
_03 LDA TEMP1
SEC
SBC TEMP8
STA TEMP1
JMP MOVE_SAUCERY
_02 LDA TEMP1
CLC
ADC TEMP8
STA TEMP1
JMP MOVE_SAUCERY
_01 LDA TEMP4
BNE _03
BEQ _02
MOVE_SAUCERY LDA GROUND_SPEED
LSR
LSR
LSR
LSR
CLC
ADC #$01
STA TEMP8
LDA TEMP5 ; ADD OR SUBTRACT Y VELOCITY
CMP #$8C
BCC _01
LDA TEMP2
SEC
SBC TEMP8
STA TEMP2
JMP _02
_01 LDA TEMP5
CMP #$84
BCS _02
LDA TEMP2
CLC
ADC TEMP8
STA TEMP2
_02 LDA TEMP1 ; CHECK VELOCITY LIMITS
CMP #$14
BCS _03
LDA #$14
STA TEMP1
_03 CMP #$EB
BCC _04
LDA #$EB
STA TEMP1
_04 LDA TEMP2
CMP #$14
BCS _05
LDA #$14
STA TEMP2
_05 CMP #$EB
BCC _06
LDA #$EB
STA TEMP2
_06 RTS
;--------------------------------
; CALCULATES SAUCER POSITION
; TEMP1=DIRECTION.VELOCITY
; TEMP2=Y OR X
; TEMP3=XMSB (IF NEEDED)
; TEMP4=FRACTION
;--------------------------------
CALC_SAUCER_POS LDA #$00
STA TEMP8 ; CLEAR TEMP FOR HIGH BYTE
LDA TEMP1 ; GET VELOCITY
BEQ _01 ; IF 0 NO UPDATE
CMP #$80
BEQ _01
SEC
SBC #$80 ; SUBTRACT 128
BCS _03
EOR #$FF ; IF NEGATIVE, GET ABS VALUE
CLC
ADC #$01
_03 ASL ; MULTIPLY BY 8
ROL TEMP8
ASL
ROL TEMP8
ASL
ROL TEMP8
STA TEMP7 ; TEMP 7,8 CONTAIN AMOUNT ADDED
LDA TEMP1 ; OR SUBTRACTED FROM OLD XPOS
CMP #$80
BCC _02
CLC
LDA TEMP4 ; OLD FRACTION
ADC TEMP7 ; PLUS FRACTION OFFSET
STA TEMP4
LDA TEMP2 ; OLD WHOLE #
ADC TEMP8 ; PLUS WHOLE # OFFSET
STA TEMP2
LDA #$00
ADC TEMP3 ; CHECK FOR XMSB
STA TEMP3
RTS
_02 SEC
LDA TEMP4 ; OLD FRACTION
SBC TEMP7 ; MINUS FRACTION OFFSET
STA TEMP4
LDA TEMP2 ; OLD WHOLE #
SBC TEMP8 ; MINUS WHOLE # OFFSET
STA TEMP2
LDA TEMP3 ; CHECK FOR XMSB
SBC #$00
STA TEMP3
_01 RTS ; TEMPS 2,3,4 HAVE BEEN UPDATED
;--------------------------------
; CHECKS SCREEN BORDERS
;--------------------------------
CHECK_BORDERS LDA TEMP4 ; CHECK HORIZONTAL AND VERTICAL
BNE _01 ; SCREEN BORDERS...
LDA TEMP3
