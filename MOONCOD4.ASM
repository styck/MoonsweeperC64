BCS _02
LDA #$18
STA TEMP3
BNE _02
_01 LDA TEMP3
CMP #$49
BCC _02
LDA #$48
STA TEMP3
_02 LDA TEMP5
CMP #$68
BCS _03
LDA #$68
STA TEMP5
RTS
_03 CMP #$A5
BCC _04
LDA #$A4
STA TEMP5
_04 RTS
;--------------------------------
; UPDATES SAUCER SPRITE
; TEMP1=SAUCERYPOS
; TEMP2=SAUCER.SPRITE.INDEX
;--------------------------------
UPDATE_SAUCER LDY #$00
LDA TEMP1
_02 CMP UPDATE_TBL,Y
BCC _01
INY
CPY #$07
BNE _02
_01 STY TEMP2
RTS
