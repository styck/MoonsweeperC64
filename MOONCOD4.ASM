STA BLOWUP_SND
LDA #$01 ; START KILLING SAUCER2
STA SAUCER_KILL_FLAG+1
RTS
_01 LDX SAUCER_KILL_INDEX ; INDEX INTO PIC TABLE
CPX #$04 ; 4 EXPLOSION PICS
BEQ _06
LDA SAUCER_EXPLOSION,X ; GET PICTURE
STA SAUCER_SPRITE ; UPDATE SPRITE
INC SAUCER_KILL_INDEX ; POINT TO NEXT PIC
RTS
_06 LDA #$00
