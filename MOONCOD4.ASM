JMP _08
_05 LDX SAUCER_KILL_INDEX+1 ; PIC INDEX FOR SAUCER2
CPX #$04
BEQ _07
LDA SAUCER_EXPLOSION,X ; GET EXPLOSION PIC
STA SAUCER_SPRITE+1 ; UPDATE SPRITE
INC SAUCER_KILL_INDEX+1 ; POINT TO NEXT PIC
RTS
_07 LDA #$00 ; READY TO REBUILD SAUCER2
STA SAUCER_KILL_INDEX+1
STA SAUCERY+1
STA SAUCER_STATUS+1
STA SAUCER_KILL_FLAG+1
DEC SAUCER_COUNT ; SAUCER OFF OF SCREEN
_08 STA SCORE_TEMP ; SAUCER WORTH 100 POINTS
STA SCORE_TEMP+2
LDA #$01
STA SCORE_TEMP+1
JSR DO_SCORE_ADD
RTS
