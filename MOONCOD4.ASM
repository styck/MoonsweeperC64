;--------------------------------
; SAUCER SHAPE TABLE
;--------------------------------
SAUCER_PIC_TABLE .byte $A9, $A8, $A7, $A6, $A5, $A4, $A3, $A2 ; SAUCER DOWN ON PLANET
SAUCER_DROP .byte $47, $48, $49 ; SAUCER DROPPING WITH FLAME
;--------------------------------
; CHECKS SAUCER COLLISION
;--------------------------------
SAUCER_COLLISION LDA SAUCER_KILL_FLAG
BEQ _15
JMP _01
_15 LDA SAUCER_KILL_FLAG+1
BEQ _16
JMP _05
_16 LDA TOP_COLLIDE ; GET COLLISION DATA
ORA MID_COLLIDE
TAX
ROR
ROR
BCC _02 ; SHOT HIT ANYTHING?
TXA ; GET BACK ORIGINAL DATA
ROR
BCS _03 ; SPRITE 0=SAUCER 1
ROR
ROR
BCS _04 ; SPRITE 2=SAUCER 2
_02 RTS
_03 LDA SAUCERY ; CHECK IF SAUCERS COLLIDE
SEC ; WITH EACH OTHER..
SBC SHOTY ; CHECK IF ANOTHER OBJECT WAS
BCS _09 ; ACTUALLY HIT BY SHOT
EOR #$FF
CLC
ADC #$01
_09 CMP #$10
BCS _02
LDA SAUCERXMSB
CMP SHOTX+1
BNE _02
LDA SAUCERX
SEC
SBC SHOTX
BCS _13
EOR #$FF
CLC
ADC #$01
_13 CMP #$10
BCS _02
LDA #$00 ; MOVE SHOT OFF SCREEN
STA SHOTY
STA SHOT_STATUS
STA SHOT_COUNT
STA SCNTRL_2
LDA #<BLPSND
STA BLOWUP_SND
LDA #$01
STA SAUCER_KILL_FLAG ; START KILLING SAUCER1
RTS
_04 LDA SAUCERY+1
SEC
SBC SHOTY
BCS _10
EOR #$FF
CLC
ADC #$01
_10 CMP #$10
BCS _02
LDA SAUCERXMSB+1
CMP SHOTX+1
BNE _02
LDA SAUCERX+1
SEC
SBC SHOTX
BCS _14
EOR #$FF
CLC
ADC #$01
_14 CMP #$10
BCS _02
LDA #$00 ; MOVE SHOT OFF SCREEN
