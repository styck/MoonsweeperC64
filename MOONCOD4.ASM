; FIRE SAUCER SHOT
;--------------------------------
FIRE_SAUCER_SHOT LDA SAUCER_SHOT_STATUS ; IS SHOT ALREADY ON SCREEN?
BNE _01
LDY PLANET_COLOR ; GET DIFFICULTY
DEC SAUCER_SHOT_DELAY
BNE _01
LDA SAUC_SHOT_TIMER,Y
STA SAUCER_SHOT_DELAY
LDA SAUCER_STATUS
ORA SAUCER_STATUS+1 ; IS THERE A SAUCER ON SCREEN?
BEQ _01
LDA MISS_PROBABILITY,Y ; GET PROBABILITY OF MISSING
AND RANDOM_NUMBER
STA TEMP1 ; SAVE FOR VELOCITY CALCS
LDY #$01
JSR GET_A_SPRITE ; FIND AVAILABLE SPRITE
LDA SAUCER_STATUS ; FIND LOWEST SAUCER
BEQ _02
LDA SAUCER_STATUS+1
BEQ _03
LDA SAUCERY
SEC
SBC SAUCERY+1
BCS _03
_02 LDY #$01
BNE _04
_03 LDY #$00
_04 JSR GET_SHOT_VELOCITY ; GET SHOT VELOCITY (X+Y)
LDA SAUCERY,Y
CMP #$68
BCC _01
CLC
ADC #$10
STA YSPRITE,X
